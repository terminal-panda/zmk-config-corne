#!/usr/bin/env python3
"""Generate the black hole animation for the right-hand nice!view.

Source: NASA SVS 13326, "New Visualization of a Black Hole" (public domain),
https://svs.gsfc.nasa.gov/13326. One frame of the orbiting-camera loop is
taken at a fixed camera angle; the disk streaks are then rotated around the
hole (inner rings faster) while the overall glow stays put, so the camera
looks still while the disk swirls.

Writes:
  boards/shields/nice_view_panda/widgets/blackhole.c   firmware images
  boards/shields/nice_view_panda/blackhole-preview.gif what the panel shows

Usage:
  scripts/nice-view-art.py                 # downloads the NASA clip if needed
  scripts/nice-view-art.py --video FILE    # use a local copy

Needs python3 with numpy + Pillow, and ffmpeg.
"""
import argparse
import math
import random
import subprocess
import tempfile
import urllib.request
from pathlib import Path

import numpy as np
from PIL import Image, ImageEnhance, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SHIELD = ROOT / "boards/shields/nice_view_panda"
VIDEO_URL = "https://svs.gsfc.nasa.gov/vis/a010000/a013300/a013326/BH_AccretionDisk_360_forGIF.webm"
CACHE = Path.home() / ".cache/zmk-config-corne"

SOURCE_FRAME = 105   # 0-based frame of the orbit loop: camera a little above the disk
FRAMES = 24          # animation length; frame time is set in peripheral_status.c
TILT = 0.32          # how squashed the disk ellipse looks from this angle
W, H = 68, 140       # art area on the panel, portrait (below the 20px status strip)
STAR_SEED = 4


def source_frame(video: Path) -> Image.Image:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "frame.png"
        subprocess.run(
            ["ffmpeg", "-v", "error", "-i", str(video), "-vf", f"select=eq(n\\,{SOURCE_FRAME})",
             "-frames:v", "1", str(out)],
            check=True,
        )
        return Image.open(out).convert("L").copy()


def swirl_frames(img: Image.Image) -> list[Image.Image]:
    """Rotate only the fine streaks; the blurred glow keeps the shape and bright side fixed."""
    base = np.asarray(img).astype(np.float32)
    env = np.asarray(img.filter(ImageFilter.GaussianBlur(14))).astype(np.float32)
    detail = np.clip(base / (env + 4), 0, 3)
    h, w = base.shape
    cx, cy = w / 2, h / 2
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    u, v = xx - cx, (yy - cy) / TILT
    r = np.hypot(u, v) + 1e-3
    phi = np.arctan2(v, u)
    frames = []
    for t in range(FRAMES):
        omega = 2 * math.pi * t / FRAMES * np.clip(120 / r, 0.25, 1.0)
        ph = phi - omega
        sx = np.clip(cx + r * np.cos(ph), 0, w - 1).astype(int)
        sy = np.clip(cy + r * np.sin(ph) * TILT, 0, h - 1).astype(int)
        frames.append(Image.fromarray(np.clip(env * detail[sy, sx], 0, 255).astype(np.uint8)))
    return frames


def atkinson(g: Image.Image) -> np.ndarray:
    buf = np.asarray(g).astype(np.float32).copy()
    h, w = buf.shape
    out = np.zeros((h, w), dtype=bool)
    for y in range(h):
        for x in range(w):
            old = buf[y, x]
            lit = old > 127
            out[y, x] = lit
            err = (old - (255 if lit else 0)) / 8
            for dx, dy in ((1, 0), (2, 0), (-1, 1), (0, 1), (1, 1), (0, 2)):
                if 0 <= x + dx < w and y + dy < h:
                    buf[y + dy, x + dx] += err
    return out


def panel_art(frame: Image.Image, stars: list[tuple[int, int]]) -> np.ndarray:
    """Portrait W x H, True = lit pixel on the panel."""
    g = ImageEnhance.Contrast(ImageEnhance.Brightness(frame).enhance(1.5)).enhance(1.4)
    core = g.crop((130, 130, 670, 670)).resize((W, W), Image.LANCZOS)
    canvas = Image.new("L", (W, H), 0)
    canvas.paste(core, (0, (H - W) // 2))
    lit = atkinson(canvas)
    dark = np.asarray(canvas) < 8
    for x, y in stars:
        if dark[y, x]:
            lit[y, x] = True
    return lit


def encode(lit: np.ndarray) -> tuple[int, int, bytes]:
    """LVGL I1 bytes for the landscape image the firmware draws (rotated back from portrait)."""
    land = np.rot90(lit, k=-1)                     # portrait -> landscape, 140 x 68
    h, w = land.shape
    stride = (w + 7) // 8
    data = bytearray()
    for row in land:
        bits = np.zeros(stride * 8, dtype=bool)
        bits[:w] = row
        data += np.packbits(bits).tobytes()
    return w, h, bytes(data)


def write_c(images: list[tuple[int, int, bytes]]) -> None:
    lines = [
        "/*",
        " * Black hole animation for the peripheral nice!view.",
        " * Generated by scripts/nice-view-art.py from NASA SVS 13326 (public domain).",
        " * Do not edit by hand.",
        " */",
        "",
        "#include <lvgl.h>",
        "",
        "#ifndef LV_ATTRIBUTE_MEM_ALIGN",
        "#define LV_ATTRIBUTE_MEM_ALIGN",
        "#endif",
        "",
        "// Index 1 = lit pixel on the panel.",
        "#if CONFIG_NICE_VIEW_WIDGET_INVERTED",
        "#define BLACKHOLE_PALETTE 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff,",
        "#else",
        "#define BLACKHOLE_PALETTE 0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,",
        "#endif",
        "",
    ]
    for i, (w, h, data) in enumerate(images):
        lines.append(f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t blackhole_{i:02d}_map[] = {{")
        lines.append("    BLACKHOLE_PALETTE")
        for off in range(0, len(data), 18):
            lines.append("    " + " ".join(f"0x{b:02x}," for b in data[off:off + 18]))
        lines.append("};")
        lines.append("")
        lines.append(f"static const lv_image_dsc_t blackhole_{i:02d} = {{")
        lines.append("    .header.cf = LV_COLOR_FORMAT_I1,")
        lines.append("    .header.magic = LV_IMAGE_HEADER_MAGIC,")
        lines.append(f"    .header.w = {w},")
        lines.append(f"    .header.h = {h},")
        lines.append(f"    .data_size = {len(data) + 8},")
        lines.append(f"    .data = blackhole_{i:02d}_map,")
        lines.append("};")
        lines.append("")
    lines.append("const lv_image_dsc_t *const blackhole_frames[] = {")
    for i in range(len(images)):
        lines.append(f"    &blackhole_{i:02d},")
    lines.append("};")
    lines.append("")
    lines.append(f"const uint32_t blackhole_frame_count = {len(images)};")
    (SHIELD / "widgets/blackhole.c").write_text("\n".join(lines) + "\n")


def write_preview(arts: list[np.ndarray]) -> None:
    lit, dark, zoom = (222, 224, 216), (30, 31, 36), 4
    frames = []
    for a in arts:
        rgb = np.where(a[..., None], lit, dark).astype(np.uint8)
        frames.append(Image.fromarray(rgb).resize((W * zoom, H * zoom), Image.NEAREST))
    frames[0].save(SHIELD / "blackhole-preview.gif", save_all=True, append_images=frames[1:],
                   duration=120, loop=0)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--video", type=Path, help="local copy of the NASA orbit clip")
    args = ap.parse_args()

    video = args.video
    if video is None:
        video = CACHE / Path(VIDEO_URL).name
        if not video.exists():
            CACHE.mkdir(parents=True, exist_ok=True)
            print(f"downloading {VIDEO_URL}")
            urllib.request.urlretrieve(VIDEO_URL, video)

    random.seed(STAR_SEED)
    stars = [(random.randrange(W), random.randrange(H)) for _ in range(30)]
    arts = [panel_art(f, stars) for f in swirl_frames(source_frame(video))]
    write_c([encode(a) for a in arts])
    write_preview(arts)
    print(f"wrote {SHIELD / 'widgets/blackhole.c'} ({len(arts)} frames)")
    print(f"wrote {SHIELD / 'blackhole-preview.gif'}")


if __name__ == "__main__":
    main()
